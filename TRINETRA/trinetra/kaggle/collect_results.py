"""Collect every *_report.json + fusion_compare.json in a folder into results/RESULTS.md and results.json.

This is the ONLY path by which numbers reach docs/14_RESULTS_LOG.md, the deck and the dashboard (rule 2).
Multi-seed reports of the same model are summarized as mean ± sd. Nothing is invented: missing = "not measured".
Run: python kaggle/collect_results.py --inp /kaggle/working --out /kaggle/working/results [--pack prototype-v1]
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import re
from collections import defaultdict

from statistics import fmean, pstdev   # stdlib only, so merging works anywhere (np.std == pstdev)

KEYS = ["oof_roc_auc", "oof_pr_auc", "oof_recall_at_fpr05", "test_roc_auc", "test_pr_auc", "test_recall_at_fpr05",
        "value_score_calibrated", "admitted", "value_score_model", "ece_crossfit_calibrated", "test_ece_calibrated", "test_n",
        "value_score", "ece", "deploy_learned", "gain_vs_rule_mean", "gain_vs_rule_lcb95", "feasible",
        "detect_rate_raw", "detect_rate_validated", "false_alarm_video_rate_raw", "false_alarm_video_rate_validated",
        "false_alarm_frames_raw", "false_alarm_frames_validated", "n_videos", "n_pos", "n_neg",
        "meta_minus_best_auc_mean", "gain_vs_tuned_rule_mean", "gain_vs_tuned_rule_lcb95",
        "stack_video_J", "clip_video_J", "fire_cnn_video_J",
        "fa_thr90_probe_base_mean", "fa_thr90_probe_conf_mean", "fa_thr90_stack_base_mean", "fa_thr90_stack_conf_mean",
        "test_auc_probe_base", "test_auc_probe_conf"]


def flat(rep):
    out = {k: rep[k] for k in KEYS if k in rep}
    for sname, st in (rep.get("stress") or {}).items():
        for k in ("fa_rate_at_0p5_cal", "fa_rate_at_pstar_cal", "mean_prob_neg_cal", "recall_at_0p5_cal"):
            if k in st:
                out[f"stress:{sname}:{k}"] = st[k]
    cal = rep.get("calibration") or {}
    for k in ("ece", "brier"):
        if k in cal:
            out[f"raw_{k}"] = cal[k]
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--inp", default="/kaggle/working"); ap.add_argument("--out", default="/kaggle/working/results")
    ap.add_argument("--pack", default="prototype-v1", help="dataset pack label (never mix with older results)")
    a = ap.parse_args(argv)
    os.makedirs(a.out, exist_ok=True)
    groups = defaultdict(list)
    for f in sorted(glob.glob(os.path.join(a.inp, "**", "*_report.json"), recursive=True)):
        if re.match(r"(rl_env|glof_physics|geo_physics)", os.path.basename(f)):
            continue                       # summarized in the geo section instead
        rep = json.load(open(f))
        name = re.sub(r"_s\d+_report\.json$|_report\.json$", "", os.path.basename(f))
        groups[name].append({"file": os.path.relpath(f, a.inp), "run_id": rep.get("run_id"), "seed": rep.get("seed"),
                             **flat(rep), "dry_run": rep.get("dry_run", False)})
    summary = {}
    for name, runs in groups.items():
        s = {"n_seeds": len(runs), "runs": runs}
        for k in {k for r in runs for k in r if isinstance(r[k], (int, float)) and not isinstance(r[k], bool) and k != "seed"}:
            v = [r[k] for r in runs if isinstance(r.get(k), (int, float)) and not isinstance(r.get(k), bool)]
            s[k] = {"mean": float(fmean(v)), "sd": float(pstdev(v))}
        for k in ("admitted", "deploy_learned"):
            vals = [r[k] for r in runs if k in r]
            if vals:
                s[k] = f"{sum(map(bool, vals))}/{len(vals)}"
        summary[name] = s
    # ---- geo / GLOF / RL-env reports (nested structures, summarized separately)
    geo = {}
    for pat in ("geo_physics_s*_report.json", "glof_physics_report.json", "rl_env*_report.json"):
        for f in sorted(glob.glob(os.path.join(a.inp, "**", pat), recursive=True)):
            r = json.load(open(f)); geo[os.path.relpath(f, a.inp)] = r
    fusion = None
    fc = glob.glob(os.path.join(a.inp, "**", "fusion_compare.json"), recursive=True)
    if fc:
        fusion = json.load(open(fc[0]))
    res = {"pack": a.pack, "models": summary, "fusion": fusion, "geo": geo,
           "dry_run_present": any(r.get("dry_run") for g in groups.values() for r in g)}
    json.dump(res, open(os.path.join(a.out, "results.json"), "w"), indent=2)

    def fmt(s, k):
        return f"{s[k]['mean']:.3f} ± {s[k]['sd']:.3f}" if k in s else "not measured"
    L = [f"# RESULTS (pack: {a.pack}) — auto-generated by kaggle/collect_results.py", "",
         "Labels: every number below is OUR RESULT on the prototype pack subset; NOT comparable to full-benchmark papers.", ""]
    if res["dry_run_present"]:
        L += ["**WARNING: some runs are --dry-run (random weights). Do not present them.**", ""]
    L += ["| model | seeds | admitted | ROC-AUC (OOF) | recall@FPR5% (OOF) | ROC-AUC (held-out) | recall@FPR5% (held-out) "
          "| value score (OOF raw / calibrated) | ECE raw | ECE calibrated (OOF) | ECE calibrated (held-out) |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, s in sorted(summary.items()):
        vs = "value_score_model" if "value_score_model" in s else "value_score"
        L.append(f"| {name} | {s['n_seeds']} | {s.get('admitted', '-')} | {fmt(s, 'oof_roc_auc')} | {fmt(s, 'oof_recall_at_fpr05')} "
                 f"| {fmt(s, 'test_roc_auc')} | {fmt(s, 'test_recall_at_fpr05')} | {fmt(s, vs)} / {fmt(s, 'value_score_calibrated')} "
                 f"| {fmt(s, 'raw_ece') if 'raw_ece' in s else fmt(s, 'ece')} "
                 f"| {fmt(s, 'ece_crossfit_calibrated')} | {fmt(s, 'test_ece_calibrated')} |")
    if "offline_rl" in summary:
        s = summary["offline_rl"]
        L += ["", f"Offline RL: deploy_learned {s.get('deploy_learned', '-')}, gain vs rule baseline {fmt(s, 'gain_vs_rule_mean')}, "
              f"95% LCB {fmt(s, 'gain_vs_rule_lcb95')} (deploy only if LCB > 0)."]
    stress_rows = [(n, k, s[k]) for n, s in sorted(summary.items()) for k in sorted(s) if k.startswith("stress:")]
    if stress_rows:
        L += ["", "## Confuser / stress sets (false alarms on things that are NOT fire)", "", "| model | set | metric | value |", "|---|---|---|---|"]
        for n, k, v in stress_rows:
            _, sset, metric = k.split(":")
            L.append(f"| {n} | {sset} | {metric} | {v['mean']:.3f} ± {v['sd']:.3f} |")
    if "video" in summary:
        s = summary["video"]
        L += ["", "## Video (FireSense): raw per-frame alarm vs temporal validator", "",
              "| metric | raw | validated |", "|---|---|---|",
              f"| detection rate (fire/smoke videos) | {fmt(s, 'detect_rate_raw')} | {fmt(s, 'detect_rate_validated')} |",
              f"| false-alarm rate (negative videos) | {fmt(s, 'false_alarm_video_rate_raw')} | {fmt(s, 'false_alarm_video_rate_validated')} |",
              f"| false-alarm frames (negative videos) | {fmt(s, 'false_alarm_frames_raw')} | {fmt(s, 'false_alarm_frames_validated')} |",
              f"Videos: {fmt(s, 'n_videos')} (pos {fmt(s, 'n_pos')}, neg {fmt(s, 'n_neg')}). Small n: quote counts."]
    if fusion:
        L += ["", f"## Fusion comparison (SYNTHETIC PAIRING, sources {fusion['sources']}, fake_frac {fusion['fake_frac']}, "
              f"{len(fusion['seeds'])} seeds)", "", "| rule | value score | ECE | miss rate | false-alarm rate |", "|---|---|---|---|---|"]
        for rule, m in fusion["rules"].items():
            g = lambda k: f"{m[k]['mean']:.3f} ± {m[k]['sd']:.3f}"  # noqa: E731
            L.append(f"| {rule} | {g('value_score')} | {g('ece')} | {g('miss_rate')} | {g('false_alarm_rate')} |")
    for f, r in geo.items():
        if r.get("name") == "geo_physics":
            L += ["", f"## Landslide physics hindcast (REAL events, NASA GLC + POWER + Copernicus DEM; {r['n']} rows, {r['n_pos']} events, "
                  f"{r['n_blocks']} spatial blocks; case-control)", "", "| score | ROC-AUC | PR-AUC | recall@FPR5% |", "|---|---|---|---|"]
            for k, v in r["scores"].items():
                L.append(f"| {k} | {v.get('roc_auc', float('nan')):.3f} | {v.get('pr_auc', float('nan')):.3f} | {v.get('recall_at_fpr05', float('nan')):.3f} |")
            d = r["physics_minus_rain_auc"]; h = r["hybrid_minus_rain_auc"]
            L.append(f"\nPhysics minus rain AUC {d['mean']:+.3f} (95% CI {d['ci95'][0]:+.3f} to {d['ci95'][1]:+.3f}); "
                     f"hybrid minus rain {h['mean']:+.3f} (CI {h['ci95'][0]:+.3f} to {h['ci95'][1]:+.3f}).")
        elif r.get("name") == "glof_physics":
            L += ["", f"## GLOF empirical relations (HMAGLOFDB {r['source']})", "", "| relation | n | exponent (95% CI) | R2 (log) |", "|---|---|---|---|"]
            for k in ("area_volume", "volume_peakQ"):
                v = r[k]
                if "exponent" in v:
                    L.append(f"| {k} | {v['n']} | {v['exponent']:.2f} ({v['exponent_ci95'][0]:.2f}-{v['exponent_ci95'][1]:.2f}) | {v['r2_log']:.2f} |")
        elif str(r.get("name", "")).startswith("rl_env"):
            L += ["", f"## RL in physics simulator ({r['name']}, C_miss={r['C_miss']}, {r['n_seasons']} real rain seasons; SIMULATOR, not field)", "",
                  "| policy | return (mean) | miss rate | alarm days/season |", "|---|---|---|---|"]
            for k, v in r["policies"].items():
                L.append(f"| {k} | {v['return_mean']:.1f} | {v['miss_rate'] if v['miss_rate'] is None else round(v['miss_rate'], 3)} | {v['alarm_days_per_season']:.1f} |")
            if "gain_vs_rule_lcb95" in r:
                L.append(f"\nLearned vs best rule ({r.get('best_rule')}): gain {r['gain_vs_rule_mean']:+.2f}, 95% LCB {r['gain_vs_rule_lcb95']:+.2f} -> deploy {r['deploy_learned']}.")
    # ---- landslide META-FUSION (REAL pairing): rule table, mean ± sd over seeds
    gf = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(a.inp, "**", "geo_fusion_s*_report.json"), recursive=True))]
    if gf:
        r0 = gf[0]
        L += ["", f"## Landslide META-FUSION (REAL pairing: every expert scores the same place and day; {r0['n']} rows, "
              f"{r0['n_pos']} events, {r0['n_blocks']} blocks; {len(gf)} seed(s); Geo-PINN {r0['pinn']})", "",
              f"Gate (calibrated FM-1 vs climatology and rain-only on cost, 95% CI): admitted {sum(bool(g['admitted']) for g in gf)}/{len(gf)}", "",
              "| rule | ROC-AUC | recall@FPR5% | ECE | value score | miss rate @p* | false alarms @p* |", "|---|---|---|---|---|---|---|"]
        for rule in r0["rules"]:
            def ms(k, rule=rule):
                v = [g["rules"][rule][k] for g in gf if rule in g["rules"] and g["rules"][rule].get(k) is not None]
                return f"{fmean(v):.3f} ± {pstdev(v):.3f}" if v else "-"
            L.append(f"| {rule} | {ms('roc_auc')} | {ms('recall_at_fpr05')} | {ms('ece')} | {ms('value_score')} | {ms('miss_rate')} | {ms('false_alarm_rate')} |")
        d = [g["fm1_minus_rain_auc"]["mean"] for g in gf]
        L.append(f"\nFM-1 minus rain-only AUC: {fmean(d):+.3f} (seed 0 95% CI {r0['fm1_minus_rain_auc']['ci95'][0]:+.3f} to "
                 f"{r0['fm1_minus_rain_auc']['ci95'][1]:+.3f}). Case-control design: AUC is the headline, value score is indicative.")
    open(os.path.join(a.out, "RESULTS.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
